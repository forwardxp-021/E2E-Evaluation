        cfg=json.loads((root/'configs/rbr_v2_uonly_v1/seed3407.json').read_text())
        # Real S3-P0 provenance lacks a source certificate; must fail before constructing a model.
        legacy=root/'docs/stageR/s3_p0_rbr_training_entry/S3_P0_U_Data_Split_Manifest_v1.json'
        with self.assertRaisesRegex(ValueError,'RAW_SEGMENT_DISJOINTNESS_NOT_ESTABLISHED'):
            entry_gate(legacy,cfg)
        wrong=dict(cfg,primary_seed=3408)
        with self.assertRaisesRegex(ValueError,'Unauthorized seed'):
            entry_gate(legacy,wrong)
        self.assertFalse(selection_improved(1-1e-7,1))
        self.assertFalse(selection_improved(1,1))
        self.assertTrue(selection_improved(1-2e-6,1))
        norm=Normalizer(2)
        norm.update([[2,999],[4,999]],[[True,False],[True,False]],'train')
        self.assertEqual(norm.state()['mean'],[3,0])
        self.assertEqual(norm.state()['zero_support'],[1])


