class PhysicalTests(unittest.TestCase):
    def test_official_center_rigid_body_velocity_shift(self):
        from nuplan.common.actor_state.ego_state import EgoState
        from nuplan.common.actor_state.state_representation import StateSE2,StateVector2D,TimePoint
        from nuplan.common.actor_state.vehicle_parameters import get_pacifica_parameters
        from nuplan.common.actor_state.tracked_objects import TrackedObjects
        from nuplan.planning.simulation.observation.observation_type import DetectionsTracks
        vehicle=get_pacifica_parameters()
        e=EgoState.build_from_rear_axle(StateSE2(10,20,np.pi/2),StateVector2D(8,.2),
            StateVector2D(0,0),0,TimePoint(1700000000000000),vehicle,angular_vel=.4)
        v=from_nuplan([e],[DetectionsTracks(TrackedObjects([]))],{},'body')
        # Independent rigid-body v_center = v_rear + omega cross offset.
        d=e.car_footprint.rear_axle_to_center_dist
        self.assertAlmostEqual(float(v['x'][0,2]),8,places=5)
        self.assertAlmostEqual(float(v['x'][0,3]),.2+.4*d,places=5)
        self.assertEqual(int(v['ego_valid'].sum()),1)  # correctly ineligible for training

    def test_all_five_slots_and_time_axis(self):
        s=five_slot_fixture(); w=from_waymo(s,'1'); e,o=nuplan_fixture(s)
        lanes=nuplan_map_fixture()
        n=from_nuplan(e,o,lanes,'body')
        np.testing.assert_array_equal(w['channel_valid'],n['channel_valid'])
        np.testing.assert_array_equal(w['slot_ids'],np.tile(['2','3','4','5','6'],(80,1)))
        np.testing.assert_allclose(w['x'],n['x'],atol=4e-5,rtol=2e-6)
        # Four different analytical polynomial gaps establish slot/time layout independently.
        t=np.arange(80)*.1
        for j,y,v,x0 in [(1,10,7,-4),(2,-10,9,-4),(3,15,7.5,4),(4,-15,8.5,4)]:
            k=8+15*j
            np.testing.assert_allclose(w['x'][:,k+1],y+(v-8)*t,atol=4e-5)
            np.testing.assert_allclose(w['x'][:,k+2],-x0,atol=4e-5)
            np.testing.assert_allclose(w['x'][:,k+3],v-8,atol=4e-5)
            np.testing.assert_allclose(w['x'][1:,k+14],0,atol=1e-6)
        lanes['100'].topology_source='nuplan_connector_adjacent_unknown'
        partial=from_nuplan(e,o,lanes,'body')
        self.assertFalse(partial['channel_valid'][:,23:].any())
        self.assertTrue(partial['channel_valid'][:,8].all())

    def test_real_source_interfaces_against_independent_oracle(self):
        from tools.waymo_lane_utils import extract_lane_polylines
        s=physical_fixture(); w=from_waymo(s,'1'); e,o=nuplan_fixture(s)
        n=from_nuplan(e,o,extract_lane_polylines(s),'body')
        np.testing.assert_array_equal(w['channel_valid'],n['channel_valid'])
        np.testing.assert_allclose(w['x'],n['x'],atol=4e-5,rtol=1e-6)
        t=np.arange(80)*.1; gap=20-2*t-.05*t*t; dist=np.sqrt(gap*gap+.25)
        oracle=np.zeros((80,83)); mask=np.zeros((80,83),bool)
        oracle[:,:6]=np.stack([8*t+.25*t*t,.3*t,8+.5*t,np.full(80,.3),np.zeros(80),np.sqrt((8+.5*t)**2+.09)],1)
        mask[:,:6]=True
        oracle[1:,6]=np.diff(np.sqrt((8+.5*t)**2+.09))/.1; mask[1:,6:8]=True
        ns=np.sqrt((6+.4*t)**2+.09)
        closing=gap*(2+.1*t)/dist
        for j in range(5):
            k=8+15*j; mask[:,k]=True
            oracle[:,k+9:k+11]=999
        k=8; oracle[:,k]=1
        oracle[:,k+1:k+15]=np.stack([gap,np.full(80,-.5),-2-.1*t,np.zeros(80),dist,
            gap,np.full(80,-.5),closing,np.minimum(dist/closing,999),gap/(8+.5*t),
            ns,np.r_[0,np.diff(ns)/.1],.1+.02*t,np.r_[0,np.full(79,.02)]],1)
        mask[:,k+1:k+15]=True; mask[0,[k+12,k+14]]=False
        np.testing.assert_array_equal(w['channel_valid'],mask)
        np.testing.assert_allclose(w['x'],oracle,atol=4e-5,rtol=2e-6)
        self.assertEqual(len(NAMES),83)

    def test_co_moving_no_double_subtraction(self):
        t=np.arange(80)*.1; e=np.stack([8*t,np.zeros(80),np.full(80,8),np.zeros(80),np.zeros(80),np.ones(80)],1)
        a=e.copy(); a[:,0]+=20
        neighbors=np.zeros((80,5,6)); neighbors[:,0]=a
        ids=np.full((80,5),''); ids=ids.astype('U8'); ids[:,0]='a'
        x=canonical(e,neighbors,ids,np.ones(80,bool))
        np.testing.assert_allclose(x['x'][:,16],0)
        self.assertFalse(x['channel_valid'][:,17].any())
        np.testing.assert_allclose(x['x'][:,18],2.5)

    def test_world_yaw_and_identity_switch(self):
        e=np.zeros((80,6)); e[:,5]=1; e[:,4]=np.arange(80)*.01
        n=np.zeros((80,5,6)); n[:,0,5]=1; n[:,0,0]=20; n[:,0,4]=3.13
        ids=np.full((80,5),'',dtype='U8'); ids[:,0]='a'; ids[40:,0]='b'
        v=canonical(e,n,ids,np.ones(80,bool))
        np.testing.assert_allclose(v['x'][:,22],0)
        self.assertFalse(v['channel_valid'][40,22]); self.assertFalse(v['channel_valid'][40,20])
        self.assertGreater(abs(v['x'][70,21]-v['x'][10,21]),.5)

    def test_physical_clock_missing_and_wrap(self):
        a=np.zeros((81,6)); a[:,0]=np.arange(81)*.1; a[:,2]=1; a[:,5]=1
        a[:,4]=3.13+np.arange(81)*.003
        times=1700000000000000+np.arange(81,dtype=np.int64)*100000
        out=resample(a,times,times[0]); np.testing.assert_allclose(out[:,0],np.arange(80)*.1)
        a[10,5]=0; out=resample(a,times,times[0]); self.assertEqual(out[10,5],0)
        bad=times.copy(); bad[20]=bad[19]
        with self.assertRaises(ValueError): resample(a,bad,times[0])
        shifted=resample(a,times+50000,times[0]); self.assertEqual(shifted[0,5],0)
        self.assertEqual(shifted[10,5],0)
        with self.assertRaises(ValueError): from_nuplan([],[],{},'UNKNOWN')
        e=np.zeros((80,6)); e[:,5]=1
        e[:,4]=(3.13+np.arange(80)*.01+np.pi)%(2*np.pi)-np.pi
        v=canonical(e,np.zeros((80,5,6)),np.full((80,5),'',dtype='U8'),np.ones(80,bool))
        np.testing.assert_allclose(v['x'][1:,7],.1,atol=1e-7)

