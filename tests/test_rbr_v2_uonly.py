def physical_fixture():
    """Independent polynomial world motion, not generated by canonical equations."""
    s=Scenario(); s.scenario_id='ANALYTICAL_ONLY'
    s.timestamps_seconds.extend(np.arange(80)*.1)
    for aid in (1,2):
        tr=s.tracks.add(id=aid,object_type=1)
        for t in np.arange(80)*.1:
            if aid==1:
                tr.states.add(center_x=-.3*t,center_y=8*t+.25*t*t,
                              velocity_x=-.3,velocity_y=8+.5*t,heading=np.pi/2,valid=True)
            else:
                tr.states.add(center_x=.5-.3*t,center_y=20+6*t+.2*t*t,
                              velocity_x=-.3,velocity_y=6+.4*t,heading=np.pi/2+.1+.02*t,valid=True)
    mf=s.map_features.add(id=100)
    for y in (-100,0,100,200):
        mf.lane.polyline.add(x=0,y=y)
    return s


def nuplan_fixture(s):
    from nuplan.common.actor_state.ego_state import EgoState
    from nuplan.common.actor_state.state_representation import StateSE2, StateVector2D, TimePoint
    from nuplan.common.actor_state.vehicle_parameters import get_pacifica_parameters
    from nuplan.common.actor_state.agent import Agent
    from nuplan.common.actor_state.oriented_box import OrientedBox
    from nuplan.common.actor_state.scene_object import SceneObjectMetadata
    from nuplan.common.actor_state.tracked_objects_types import TrackedObjectType
    from nuplan.common.actor_state.tracked_objects import TrackedObjects
    from nuplan.planning.simulation.observation.observation_type import DetectionsTracks
    ego=[]; obs=[]
    for i,t in enumerate(np.arange(80)*.1):
        # nuPlan body-frame vector includes lateral component; speed*cos(h) would be wrong.
        es=s.tracks[0].states[i]
        ego.append(EgoState.build_from_center(StateSE2(es.center_x,es.center_y,np.pi/2),
            StateVector2D(es.velocity_y,-es.velocity_x),StateVector2D(.5,0),0,
            TimePoint(1700000000000000+i*100000),get_pacifica_parameters()))
        agents=[]
        for tr in s.tracks[1:]:
            a=tr.states[i]
            ag=Agent(TrackedObjectType.VEHICLE,OrientedBox(StateSE2(a.center_x,a.center_y,a.heading),4.5,1.8,1.5),
                StateVector2D(a.velocity_x,a.velocity_y),SceneObjectMetadata(1700000000000000+i*100000,
                'token_'+str(tr.id)+'_'+str(i),track_token=str(tr.id),track_id=tr.id))
            agents.append(ag)
        obs.append(DetectionsTracks(TrackedObjects(agents)))
    return ego,obs


def five_slot_fixture():
    s=physical_fixture()
    s.map_features[0].lane.left_neighbors.add(feature_id=101,self_start_index=0,self_end_index=3,
        neighbor_start_index=0,neighbor_end_index=3)
    s.map_features[0].lane.right_neighbors.add(feature_id=102,self_start_index=0,self_end_index=3,
        neighbor_start_index=0,neighbor_end_index=3)
    for lane_id,x in [(101,-4),(102,4)]:
        lane=s.map_features.add(id=lane_id).lane
        for y in (-100,0,100,200): lane.polyline.add(x=x,y=y)
    for aid,x,y,v in [(3,-4,10,7),(4,-4,-10,9),(5,4,15,7.5),(6,4,-15,8.5)]:
        tr=s.tracks.add(id=aid,object_type=1)
        for t in np.arange(80)*.1:
            tr.states.add(center_x=x-.3*t,center_y=y+v*t+.25*t*t,velocity_x=-.3,velocity_y=v+.5*t,
                          heading=np.pi/2,valid=True)
    # Keep this fixture in its declared lane for the complete window. The other
    # fixture separately tests lateral velocity/sideslip, without asserting a fixed lane.
    for tr in s.tracks:
        for i,a in enumerate(tr.states):
            a.center_x += .3*i*.1; a.velocity_x=0
    return s


