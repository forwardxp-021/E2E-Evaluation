#!/usr/bin/env python3
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import argparse
import importlib.util
import json
import shutil
from pathlib import Path


def write_json(path: Path, obj) -> None:
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")


def validate_dir(path: Path, label: str, errors: list) -> None:
    if not path.exists():
        errors.append(f"{label} does not exist: {path}")
    elif not path.is_dir():
        errors.append(f"{label} is not a directory: {path}")


def nuplan_available() -> bool:
    return importlib.util.find_spec("nuplan") is not None


def run(args) -> int:
    out_dir = Path(args.output_dir)
    if out_dir.exists() and any(out_dir.iterdir()) and not args.overwrite:
        raise FileExistsError(f"output_dir exists and is not empty: {out_dir}. Use --overwrite.")
    if out_dir.exists() and args.overwrite:
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    data_root = Path(args.nuplan_data_root).expanduser()
    maps_root = Path(args.nuplan_maps_root).expanduser()
    exp_root = Path(args.nuplan_exp_root).expanduser()

    errors = []
    validate_dir(data_root, "nuplan_data_root", errors)
    validate_dir(maps_root, "nuplan_maps_root", errors)
    validate_dir(exp_root, "nuplan_exp_root", errors)

    has_nuplan = nuplan_available()
    if not has_nuplan:
        errors.append(
            "nuPlan devkit is not installed in this Python environment. "
            "Install nuplan-devkit in a Python 3.9 Ubuntu/WSL2 environment before running real rollout export."
        )

    manifest = {
        "stage": "stage7A_nuplan_rollout_export",
        "status": "blocked" if errors else "ready_for_nuplan_integration",
        "planner_variant": args.planner_variant,
        "scenario_filter": args.scenario_filter,
        "max_scenarios": int(args.max_scenarios),
        "nuplan_data_root": str(data_root),
        "nuplan_maps_root": str(maps_root),
        "nuplan_exp_root": str(exp_root),
        "output_dir": str(out_dir),
        "nuplan_devkit_available": bool(has_nuplan),
        "errors": errors,
        "todo": [
            "Integrate nuPlan scenario builder for the requested scenario_filter.",
            "Implement conservative and aggressive configurable planner variants.",
            "Run closed-loop planner simulation for the same scenario set.",
            "Export ego rollout and neighbor context to CSV or parquet with Stage 7A rollout schema.",
        ],
        "expected_rollout_schema": {
            "required": [
                "scenario_id",
                "policy_id",
                "timestamp",
                "ego_x",
                "ego_y",
                "ego_vx",
                "ego_vy",
                "ego_speed",
                "ego_accel",
                "ego_heading",
                "ego_yaw_rate",
            ],
            "optional_neighbor_fields": [
                "neighbor_id",
                "neighbor_x",
                "neighbor_y",
                "neighbor_vx",
                "neighbor_vy",
                "neighbor_speed",
                "neighbor_heading",
                "neighbor_type",
            ],
        },
    }
    write_json(out_dir / "rollout_export_manifest.json", manifest)
    (out_dir / "README.md").write_text(
        "# Stage 7A nuPlan rollout export\n\n"
        "This directory was created by `tools/stage7a_export_nuplan_rollouts.py`.\n\n"
        "No fake rollouts are generated by this skeleton. Real rollout export requires "
        "nuPlan devkit integration in a Python 3.9 Ubuntu/WSL2 environment.\n\n"
        f"Status: `{manifest['status']}`\n",
        encoding="utf-8",
    )

    if errors:
        print("Stage 7A rollout export is not ready to run real nuPlan simulation:")
        for err in errors:
            print(f"- {err}")
        print(f"Wrote manifest: {out_dir / 'rollout_export_manifest.json'}")
        return 2

    print("nuPlan paths and devkit availability checks passed.")
    print("This skeleton has not yet implemented real nuPlan rollout simulation.")
    print(f"Wrote manifest: {out_dir / 'rollout_export_manifest.json'}")
    return 0


def parse_args():
    parser = argparse.ArgumentParser(description="Skeleton exporter for Stage 7A nuPlan same-scenario policy rollouts.")
    parser.add_argument("--nuplan_data_root", required=True)
    parser.add_argument("--nuplan_maps_root", required=True)
    parser.add_argument("--nuplan_exp_root", required=True)
    parser.add_argument("--scenario_filter", default="mini")
    parser.add_argument("--planner_variant", choices=["conservative", "aggressive"], required=True)
    parser.add_argument("--max_scenarios", type=int, default=20)
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--overwrite", action="store_true")
    return parser.parse_args()


if __name__ == "__main__":
    raise SystemExit(run(parse_args()))
